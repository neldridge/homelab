#!/usr/bin/env python3
"""Bound scheduled recovery generations and disposable transfer work only."""
import argparse
import datetime
import fcntl
import json
import re
import shutil
import time
import os
import stat
import tempfile
import tarfile
from contextlib import ExitStack
from pathlib import Path
from verify_bundle import verify, digest

ROOT = Path('/opt/data/homelab/backups')
GEN = re.compile(r'\d{8}T\d{6}Z')
PRIOR = re.compile(r'before-(\d{8}T\d{6}Z)\.tar')
KEEP = 7
SCRATCH_AGE = 2 * 86400

def generation_time(ident):
    return datetime.datetime.strptime(ident, '%Y%m%dT%H%M%SZ').replace(tzinfo=datetime.timezone.utc).timestamp()

def safe_tree(path):
    """Never traverse links, devices, sockets, or unexpected filesystem boundaries."""
    device = path.stat().st_dev
    for base, dirs, files in os.walk(path, followlinks=False):
        for name in dirs + files:
            child = Path(base) / name
            info = child.lstat()
            if info.st_dev != device or not (stat.S_ISDIR(info.st_mode) or stat.S_ISREG(info.st_mode)):
                raise RuntimeError('Unsafe retention path: ' + str(child))


def lock_file(path):
    fd = os.open(path, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    handle = os.fdopen(fd, 'a')
    try:
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            raise RuntimeError('Invalid lock file')
        fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        return handle
    except BaseException:
        handle.close()
        raise


def complete(path):
    if path.is_symlink() or not path.is_dir():
        return False
    try:
        manifest = path / 'manifest.json'
        return (not manifest.is_symlink() and not (path/'COMPLETE').is_symlink()
                and (path/'COMPLETE').read_text().strip() == digest(manifest)
                and json.loads(manifest.read_text())['id'] == path.name)
    except (OSError, ValueError, KeyError):
        return False

def local_plan(root, now=None):
    now = time.time() if now is None else now
    bundles = sorted((p for p in root.iterdir() if GEN.fullmatch(p.name) and complete(p)), key=lambda p:p.name, reverse=True)
    if not bundles:
        if (root/'transfers').exists() and any((root/'transfers').iterdir()):
            raise RuntimeError('No completed recovery bundle; refusing retention')
        return []
    # Check a complete recovery point before removing even disposable scratch.
    safe_tree(bundles[0])
    verify(bundles[0])
    protected = {p.name for p in bundles[:KEEP]}
    nas = {}
    for name, key in [('local-status.json','id'),('nas-status.json','bundle_id')]:
        path = root/name
        if path.is_symlink(): raise RuntimeError("Symlink status file")
        if path.exists():
            state = json.loads(path.read_text())
            protected.add(state.get(key,''))
            if name == 'nas-status.json': nas = state
    victims = [p for p in bundles if p.name not in protected]
    transfers = root/'transfers'
    if transfers.is_symlink(): raise RuntimeError('Symlink transfer root')
    if transfers.exists():
        for p in sorted(transfers.iterdir()):
            if not GEN.fullmatch(p.name) or p.is_symlink() or not p.is_dir(): continue
            # This exact tree is generated by publish_nas, never original data.
            if any(c.name not in {'recovery.tar','nas-readback.tar','published-readback.tar','readback'} or c.is_symlink() for c in p.iterdir()):
                raise RuntimeError('Unexpected transfer scratch contents')
            safe_tree(p)
            successful = nas.get('success') is True and p.name == nas.get('bundle_id')
            newest = max([p.stat().st_mtime] + [c.stat().st_mtime for c in p.rglob('*')])
            if successful or now-newest >= SCRATCH_AGE:
                victims.append(p)
    for victim in victims: safe_tree(victim)
    return victims

def prune_local(root=ROOT, apply=False):
    if root.is_symlink() or root.resolve() != root.absolute(): raise RuntimeError('Symlink backup root')
    # Serialize against both builder and publisher, including manual invocations.
    with ExitStack() as stack:
        for name in ('bundle.lock','transfer.lock'):
            stack.enter_context(lock_file(root/name))
        victims=local_plan(root)
        retained = sorted(p.name for p in root.iterdir() if GEN.fullmatch(p.name) and complete(p) and p not in victims)
        print('retained local generations: '+', '.join(retained), flush=True)
        reclaimed = 0
        for p in victims:
            size = sum(c.stat().st_size for c in p.rglob('*') if c.is_file())
            print(('remove ' if apply else 'would remove ')+str(p)+f' ({size} file bytes)',flush=True)
            if apply: shutil.rmtree(p)
            reclaimed += size
        print(('reclaimed' if apply else 'would reclaim')+f' {reclaimed} local file bytes',flush=True)
        return victims

def prune_nas(smb, current, apply=False):
    """Call only under transfer.lock after published readback succeeds."""
    if not GEN.fullmatch(current): raise ValueError('Invalid generation')
    listing=smb('cd prior; ls',45)
    names=[]
    for line in listing.splitlines():
        match=re.match(r'^\s*(before-\d{8}T\d{6}Z\.tar)\s+A\s+\d+\s',line)
        if match: names.append(match[1])
    print('preserve NAS published/recovery.tar; retained prior: '+', '.join(sorted(set(names),reverse=True)[:KEEP]),flush=True)
    # Names record the replacement time, not necessarily the archive's creation.
    for name in sorted(set(names),reverse=True)[KEEP:]:
        ident=PRIOR.fullmatch(name)[1]
        if ident <= current:
            print(('remove' if apply else 'would remove')+' NAS prior/'+name,flush=True)
            if apply: smb('del "prior/'+name+'"',45)
    # Only old, date-named incomplete uploads; never published or unknown files.
    for line in smb('cd staging; ls',45).splitlines():
        match=re.match(r'^\s*(\d{8}T\d{6}Z)\.tar\s+A\s+\d+\s',line)
        if match and match[1] < current and time.time()-generation_time(match[1]) >= SCRATCH_AGE:
            # SMB timestamps are required too: a retried upload can have an old ID.
            fields = line.split()
            try:
                modified = datetime.datetime.strptime(' '.join(fields[-5:]), '%a %b %d %H:%M:%S %Y').replace(tzinfo=datetime.timezone.utc).timestamp()
            except ValueError:
                continue
            if time.time()-modified < SCRATCH_AGE: continue
            print(('remove' if apply else 'would remove')+' NAS staging/'+match[1]+'.tar',flush=True)
            if apply: smb('del "staging/'+match[1]+'.tar"',45)

def nas_retention(apply=False):
    """Standalone preview/apply verifies the current NAS archive under both locks."""
    from publish_nas import smb
    if ROOT.is_symlink() or ROOT.resolve() != ROOT.absolute(): raise RuntimeError('Symlink backup root')
    with ExitStack() as stack:
        for name in ('bundle.lock', 'transfer.lock'):
            stack.enter_context(lock_file(ROOT/name))
        state_path = ROOT/'nas-status.json'
        if state_path.is_symlink(): raise RuntimeError('Symlink NAS status')
        state = json.loads(state_path.read_text())
        ident = state['bundle_id']
        if state.get('success') is not True or not GEN.fullmatch(ident):
            raise RuntimeError('No successful NAS evidence')
        with tempfile.TemporaryDirectory(prefix='retention-', dir=ROOT) as tmp:
            archive = Path(tmp)/'recovery.tar'
            smb(f'get published/recovery.tar "{archive}"')
            if digest(archive) != state['sha256']: raise RuntimeError('NAS checksum mismatch')
            restored = Path(tmp)/'restored'
            restored.mkdir()
            with tarfile.open(archive) as tar:
                tar.extractall(restored, filter='data')
            safe_tree(restored)
            evidence = verify(restored/ident)
            if evidence != state['validation']: raise RuntimeError('NAS verification mismatch')
            prune_nas(smb, ident, apply=apply)


if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--apply',action='store_true')
    p.add_argument('--nas',action='store_true', help='verify published NAS archive and plan NAS cleanup')
    args=p.parse_args()
    if args.nas: nas_retention(apply=args.apply)
    else: prune_local(apply=args.apply)
